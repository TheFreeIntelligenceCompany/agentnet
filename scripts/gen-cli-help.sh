#!/bin/sh
# Regenerate docs/cli-help.txt: `agentnet --help` and the help of every subcommand.
# Usage: scripts/gen-cli-help.sh            (builds target/debug/agentnet if needed)
#        AGENTNET_BIN=/path/to/agentnet scripts/gen-cli-help.sh
set -eu
cd "$(dirname "$0")/.."
BIN="${AGENTNET_BIN:-target/debug/agentnet}"
if [ -z "${AGENTNET_BIN:-}" ]; then
  cargo build -p agentnet-cli
fi
OUT=docs/cli-help.txt
: > "$OUT"
emit() {
  printf '\n===== agentnet %s --help =====\n\n' "$*" >> "$OUT"
  # shellcheck disable=SC2068
  env -u AGENTNET_HOME COLUMNS=100 "$BIN" $@ --help >> "$OUT" 2>&1
}
printf 'Generated by scripts/gen-cli-help.sh from the built binary. Do not edit by hand.\n' >> "$OUT"
emit ""
for c in init serve mcp identity contact quarantine send inbox ack status outbox trigger events discovery network doctor relay; do
  emit "$c"
done
for c in "identity show" "identity export" "identity import" "identity rotate-kem" \
         "identity revoke" "identity show-revocation" \
         "contact add" "contact list" "contact trust" "contact remove" "contact revoke" \
         "quarantine list" "quarantine release" \
         "trigger create" "trigger list" "trigger delete" \
         "discovery advertise" "discovery withdraw" "discovery list" \
         "events tail" "network status" "relay print-config"; do
  emit "$c"
done
echo "wrote $OUT"
